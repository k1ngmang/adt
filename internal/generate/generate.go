// WriteFile renders the specification and replaces a previous adtgen output.
func WriteFile(input, output, typeName, zero string) error {
	spec, err := readSchema(input, typeName, zero)
	if err != nil {
		return err
	}

	var buffer bytes.Buffer
	if err := source.Execute(&buffer, spec); err != nil {
		return err
	}
	data, err := format.Source(buffer.Bytes())
	if err != nil {
		return fmt.Errorf("format generated Go code: %w", err)
	}

	mode := os.FileMode(0o644)
	info, err := os.Lstat(output)
	switch {
	case err == nil:
		inputInfo, err := os.Stat(input)
		if err != nil {
			return err
		}
		if os.SameFile(inputInfo, info) || !info.Mode().IsRegular() {
			return fmt.Errorf("%s: output must be a regular file distinct from the input", output)
		}
		old, err := os.ReadFile(output)
		if err != nil {
			return err
		}
		if !bytes.HasPrefix(old, []byte(generatedHeader)) {
			return fmt.Errorf("%s: refusing to overwrite a file that was not generated by adtgen", output)
		}
		if bytes.Equal(old, data) {
			return nil
		}
		mode = info.Mode().Perm()
	case !errors.Is(err, os.ErrNotExist):
		return err
	}

	file, err := os.CreateTemp(filepath.Dir(output), ".adtgen-*")
	if err != nil {
		return err
	}
	defer os.Remove(file.Name())
	if err := file.Chmod(mode); err != nil {
		file.Close()
		return err
	}
	_, writeErr := file.Write(data)
	if err := errors.Join(writeErr, file.Close()); err != nil {
		return err
	}
	return os.Rename(file.Name(), output)
}
